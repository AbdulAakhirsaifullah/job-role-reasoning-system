"""
make_diagrams.py
----------------
Writes the Mermaid (.mmd) source of every knowledge diagram from the frames in
knowledge_base.py, so the diagrams always match the code.

Run:  python make_diagrams.py
Then render PNGs (optional, needs Node.js):  npx -p @mermaid-js/mermaid-cli mmdc -i diagrams/<name>.mmd -o diagrams/<name>.png -b white -s 2
Or paste a .mmd file into https://mermaid.live
"""

import os

from knowledge_base import (
    CERTIFICATION_FRAMES,
    JOB_ROLE_FRAMES,
    QUALIFICATION_FRAMES,
    SKILL_CATEGORIES,
    SKILL_FRAMES,
    create_sample_candidate,
)

DIAGRAM_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), "diagrams")


def concepts_network():
    """Class-level semantic network: IS-A, HAS-A and PART-OF."""
    return "\n".join([
        "%% Semantic network 1 of 4: concept level (IS-A, HAS-A, PART-OF)",
        "%% Generated by make_diagrams.py from knowledge_base.py",
        "flowchart BT",
        "    Person([Person])",
        "    Candidate([Candidate])",
        "    EmploymentRole([EmploymentRole])",
        "    JobRole([JobRole])",
        "    Skill([Skill])",
        "    SkillCategory([SkillCategory])",
        "    Qualification([Qualification])",
        "    Certification([Certification])",
        "    Experience([Experience in years])",
        "    Profile[[RequirementProfile]]",
        '    SkillReq[["SkillRequirement<br/>(refers to Skill)"]]',
        '    DegreeReq[["DegreeRequirement<br/>(refers to Qualification)"]]',
        '    ExpReq[["ExperienceRequirement<br/>(refers to Experience)"]]',
        '    CertReq[["CertificationRequirement<br/>(refers to Certification)"]]',
        "",
        "    Candidate -->|IS-A| Person",
        "    JobRole -->|IS-A| EmploymentRole",
        "    Candidate -->|HAS-A| Skill",
        "    Candidate -->|HAS-A| Qualification",
        "    Candidate -->|HAS-A| Experience",
        "    Candidate -->|HAS-A| Certification",
        "    Skill -->|PART-OF| SkillCategory",
        "    Skill -->|IS-A| Skill",
        "    JobRole -->|HAS-A| Profile",
        "    SkillReq -->|PART-OF| Profile",
        "    DegreeReq -->|PART-OF| Profile",
        "    ExpReq -->|PART-OF| Profile",
        "    CertReq -->|PART-OF| Profile",
    ]) + "\n"


def skills_network():
    """Skill taxonomy (IS-A between skills) and skill categories (PART-OF)."""
    lines = ["%% Semantic network 2 of 4: skill taxonomy (IS-A) and categories (PART-OF)",
             "%% Generated by make_diagrams.py from knowledge_base.py",
             "flowchart BT"]
    for cat, label in SKILL_CATEGORIES.items():
        lines.append(f'    cat_{cat}{{{{"{label}"}}}}')
    for skill_id, skill in SKILL_FRAMES.items():
        lines.append(f'    {skill_id}(("{skill["name"]}"))')
    for skill_id, skill in SKILL_FRAMES.items():
        if skill["is_a"]:
            lines.append(f"    {skill_id} ==>|IS-A| {skill['is_a']}")
    for skill_id, skill in SKILL_FRAMES.items():
        if skill["is_a"] is None:   # child skills reach their category through the parent
            lines.append(f"    {skill_id} -->|PART-OF| cat_{skill['category']}")
    return "\n".join(lines) + "\n"


def roles_network():
    """Each role and its requirement profile. IS-A JobRole and the degree and
    experience minimums are written inside each role box to keep the picture readable."""
    lines = ["%% Semantic network 3 of 4: job roles and their requirements",
             "%% Every role box IS-A JobRole (see network 1). Generated by make_diagrams.py",
             "flowchart LR"]
    for role_id, role in JOB_ROLE_FRAMES.items():
        degree = QUALIFICATION_FRAMES[role["min_degree"]]["name"]
        lines.append(f'    {role_id}["<b>{role["name"]}</b><br/>IS-A JobRole<br/>'
                     f'min degree: {degree}<br/>min experience: {role["min_experience"]} yrs"]')
    used_skills = []
    for role in JOB_ROLE_FRAMES.values():
        for skill in role["required_skills"]:
            if skill not in used_skills:
                used_skills.append(skill)
    for skill in used_skills:
        lines.append(f'    {skill}(("{SKILL_FRAMES[skill]["name"]}"))')
    for cert in sorted({c for r in JOB_ROLE_FRAMES.values() for c in r["required_certifications"]}):
        lines.append(f'    cert_{cert}[/"{CERTIFICATION_FRAMES[cert]["name"]}"/]')
    for role_id, role in JOB_ROLE_FRAMES.items():
        for skill in role["required_skills"]:
            lines.append(f"    {role_id} -->|REQUIRES-SKILL| {skill}")
        for cert in role["required_certifications"]:
            lines.append(f"    {role_id} ==>|REQUIRES-CERT| cert_{cert}")
    return "\n".join(lines) + "\n"


def instance_network():
    """One candidate (Zara) with stored facts and inferred links."""
    zara, _ = create_sample_candidate("D: Zara, skill hierarchy (TensorFlow gives ML)")
    lines = ["%% Semantic network 4 of 4: instance level for sample candidate Zara",
             "%% Solid = stored fact, dotted = inferred by the rules",
             "%% Generated by make_diagrams.py from knowledge_base.py",
             "flowchart LR",
             "    Candidate([Candidate])",
             '    zara["Zara"]',
             f'    deg["{QUALIFICATION_FRAMES[zara["degree"]]["name"]}"]',
             f'    exp["{zara["total_experience_years"]} years"]',
             '    ml_engineer["Machine Learning Engineer"]',
             '    python_developer["Python Developer"]',
             "    zara -->|INSTANCE-OF| Candidate",
             "    zara -->|HAS-A degree| deg",
             "    zara -->|HAS-A experience| exp"]
    for skill in zara["skills"]:
        lines.append(f'    {skill}(("{SKILL_FRAMES[skill]["name"]}"))')
        lines.append(f"    zara -->|HAS-SKILL| {skill}")
    lines += ['    deep_learning(("Deep Learning"))',
              '    machine_learning(("Machine Learning"))',
              "    tensorflow ==>|IS-A| deep_learning",
              "    deep_learning ==>|IS-A| machine_learning",
              "    zara -.->|inferred HAS-SKILL R1| deep_learning",
              "    zara -.->|inferred HAS-SKILL R1| machine_learning",
              "    zara -.->|inferred ELIGIBLE-FOR R6| ml_engineer",
              "    zara -.->|inferred ELIGIBLE-FOR R7| python_developer"]
    return "\n".join(lines) + "\n"


def frame_architecture():
    """Frames as boxes with slots; IS-A (inheritance) and INSTANCE-OF arrows."""
    da = JOB_ROLE_FRAMES["data_analyst"]
    return "\n".join([
        "%% Frame architecture: class frames, slots with facets, IS-A and INSTANCE-OF",
        "%% Generated by make_diagrams.py from knowledge_base.py",
        "classDiagram",
        "    direction LR",
        "    class Person {",
        "        name : text",
        "    }",
        "    class Candidate {",
        "        candidate_id : text [if-needed from name]",
        "        skills : list of skill IDs [default empty]",
        "        degree : degree ID [default none]",
        "        total_experience_years : int 0..50 [default 0]",
        "        experience_level : text [if-needed from years]",
        "        certifications : list [default empty]",
        "        target_role : role ID [default None]",
        "    }",
        "    class EmploymentRole {",
        "        name : text",
        "        description : text [default No description]",
        "    }",
        "    class JobRole {",
        "        role_id : text",
        "        required_skills : list [min 1 item]",
        "        optional_skills : list [default empty]",
        "        min_degree : degree ID [default none]",
        "        min_experience : int [default 0]",
        "        required_certifications : list [default empty]",
        "        optional_certifications : list [default empty]",
        "    }",
        "    class Skill {",
        "        name : text",
        "        category : one of 5 categories",
        "        is_a : parent skill ID [default None]",
        "    }",
        "    class Qualification {",
        "        name : text",
        "        rank : int 0..3",
        "    }",
        "    class Certification {",
        "        name : text",
        "        issuer : text [default Unknown issuer]",
        "        related_skill : skill ID",
        "    }",
        "    class data_analyst {",
        "        <<instance>>",
        f"        required_skills = {', '.join(da['required_skills'])}",
        f"        min_degree = {da['min_degree']}",
        f"        min_experience = {da['min_experience']}",
        "    }",
        "    class ali {",
        "        <<instance>>",
        "        skills = python, sql, pandas",
        "        degree = bachelors",
        "        total_experience_years = 1",
        "    }",
        "    class tensorflow {",
        "        <<instance>>",
        "        category = ai",
        "        is_a = deep_learning",
        "    }",
        "    Person <|-- Candidate : IS-A",
        "    EmploymentRole <|-- JobRole : IS-A",
        "    Candidate --> Skill : has_skill",
        "    Candidate --> Qualification : has_degree",
        "    Candidate --> Certification : has_cert",
        "    JobRole --> Skill : requires_skill",
        "    JobRole --> Qualification : min_degree",
        "    JobRole --> Certification : requires_cert",
        "    data_analyst ..> JobRole : INSTANCE-OF",
        "    ali ..> Candidate : INSTANCE-OF",
        "    tensorflow ..> Skill : INSTANCE-OF",
    ]) + "\n"


DIAGRAMS = {
    "semantic_network_1_concepts.mmd": concepts_network,
    "semantic_network_2_skills.mmd": skills_network,
    "semantic_network_3_roles.mmd": roles_network,
    "semantic_network_4_instance.mmd": instance_network,
    "frame_architecture.mmd": frame_architecture,
}


if __name__ == "__main__":
    os.makedirs(DIAGRAM_DIR, exist_ok=True)
    for filename, builder in DIAGRAMS.items():
        with open(os.path.join(DIAGRAM_DIR, filename), "w", encoding="utf-8") as f:
            f.write(builder())
        print("wrote diagrams/" + filename)
